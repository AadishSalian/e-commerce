/**
 * Returns localized string for given key (e.g. "cart.title" or "common.addToBag").
 * If the locale is a pseudo-locale, applies pseudo-localization rules.
 * If translation is missing in the requested locale, gracefully falls back to default 'en-IN'
 * and outputs diagnostic info without breaking UI.
 */
export function getTranslation(
  keyPath: string,
  localeCode: string = 'en-IN',
  params: Record<string, any> = {}
): string {
  const [namespace, key] = keyPath.split('.');
  if (!namespace || !key) return keyPath;

  const isPseudo = localeCode === 'en-XA';
  const isPseudoRTL = localeCode === 'ar-XB';

  // Find translation in requested locale
  const targetBundle = ALL_TRANSLATIONS[localeCode] || ALL_TRANSLATIONS['en-IN'];
  let template = targetBundle?.[namespace]?.[key];

  // Fallback to en-IN if missing
  if (!template) {
    template = ALL_TRANSLATIONS['en-IN']?.[namespace]?.[key];
    if (!template) {
      if (process.env.NODE_ENV !== 'production') {
        console.warn(`[i18n] Missing translation key: "${keyPath}" for locale: "${localeCode}"`);
      }
      return keyPath;
    }
  }

  // Format with ICU engine
  const formatted = formatIcuMessage(template, params, localeCode);

  // Apply pseudo transformations if requested
  if (isPseudo) {
    return pseudoLocalize(formatted);
  }
  if (isPseudoRTL) {
    return pseudoLocalizeRTL(formatted);
  }

  return formatted;
}
